/**
 * Deterministic driver for Playwright's test-generator MCP server.
 *
 * In real use an LLM agent (Claude Code / Copilot / Cursor, see .claude/agents/)
 * decides which MCP tool to call for each plan step. This script performs the
 * same tool calls without an LLM so the flow is reproducible in CI and offline
 * from any AI subscription:
 *
 *   plan step -> browser_snapshot (find ref) -> browser_type / browser_check /
 *   browser_verify_* -> generator_read_log -> generator_write_test
 *
 * Usage: npx tsx scripts/mcp-generate.ts specs/todo-basic.plan.json
 */
import { readFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

type Step =
  | { intent: string; action: 'type'; role: string; name: string; text: string }
  | { intent: string; action: 'check' | 'click'; role: string; name: string }
  | { intent: string; action: 'verifyText'; text: string };
type Scenario = { name: string; file: string; steps: Step[] };
type Plan = { suite: string; seedFile: string; scenarios: Scenario[] };

const text = (r: any): string => (r.content ?? []).map((c: any) => c.text ?? '').join('\n');
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function findRef(snapshot: string, role: string, name: string): string {
  // Snapshot lines look like: - textbox "What needs to be done?" [active] [ref=e8]
  const re = new RegExp(`${escapeRe(role)} "${escapeRe(name)}".*?\\[ref=(\\w+)\\]`);
  const m = snapshot.match(re);
  if (!m) throw new Error(`ref not found for ${role} "${name}"`);
  return m[1];
}

/** Extract ```ts blocks from the "# Steps" section of generator_read_log. */
function stepsFromLog(log: string): { title: string; code: string }[] {
  const section = log.split('# Steps')[1]?.split('# Best practices')[0] ?? '';
  const out: { title: string; code: string }[] = [];
  const re = /### (.+)\n```ts\n([\s\S]*?)```/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(section))) out.push({ title: m[1].trim(), code: m[2].trim() });
  return out;
}

async function generate(client: Client, plan: Plan, sc: Scenario) {
  const call = async (name: string, args: Record<string, unknown> = {}) => {
    const r = await client.callTool({ name, arguments: args });
    const t = text(r);
    if ((r as any).isError) throw new Error(`${name} failed: ${t}`);
    return t;
  };
  const planText = sc.steps.map((s, i) => `${i + 1}. ${s.intent}`).join('\n');
  await call('generator_setup_page', { plan: `${sc.name}\n${planText}`, seedFile: plan.seedFile });

  for (const s of sc.steps) {
    if (s.action === 'verifyText') {
      await call('browser_verify_text_visible', { text: s.text, intent: s.intent });
      continue;
    }
    const ref = findRef(await call('browser_snapshot'), s.role, s.name);
    const element = `${s.role} "${s.name}"`;
    if (s.action === 'type') await call('browser_type', { element, target: ref, text: s.text, submit: true, intent: s.intent });
    else if (s.action === 'check') await call('browser_check', { element, target: ref, intent: s.intent });
    else await call('browser_click', { element, target: ref, intent: s.intent });
  }

  const log = await call('generator_read_log');
  const body = stepsFromLog(log)
    .map((st) => `    // ${st.title}\n` + st.code.split('\n').map((l) => '    ' + l).join('\n'))
    .join('\n\n');
  const code = `// Generated by scripts/mcp-generate.ts via Playwright test MCP server. Review before committing.
import { test, expect } from '@playwright/test';
import { TodoPage } from '../../pages/TodoPage';

test.describe(${JSON.stringify(plan.suite)}, () => {
  test(${JSON.stringify(sc.name)}, async ({ page }) => {
    // seed: ${plan.seedFile}
    await new TodoPage(page).goto();

${body}
  });
});
`;
  await call('generator_write_test', { fileName: sc.file, code });
  console.log(`✔ wrote ${sc.file} (${stepsFromLog(log).length} steps)`);
}

(async () => {
  const planPath = process.argv[2] ?? 'specs/todo-basic.plan.json';
  const plan: Plan = JSON.parse(readFileSync(planPath, 'utf8'));
  for (const sc of plan.scenarios) {
    // one MCP session per scenario keeps the generator log clean
    const client = new Client({ name: 'mcp-generate', version: '1.0.0' });
    await client.connect(new StdioClientTransport({ command: 'npx', args: ['playwright', 'run-test-mcp-server'] }));
    try {
      await generate(client, plan, sc);
    } finally {
      await client.close();
    }
  }
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
